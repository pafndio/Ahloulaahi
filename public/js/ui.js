// Couleur d'avatar stable dérivée du nom.
export function avatarHue(s) {
  let h = 0;
  for (const c of String(s)) h = (h * 31 + c.charCodeAt(0)) % 360;
  return h;
}

export const fmtDate = (d, opts = { day: '2-digit', month: 'short', year: 'numeric' }) => {
  if (!d) return '—';
  const x = new Date(d.length === 10 ? `${d}T00:00:00` : d);
  return Number.isNaN(x.getTime()) ? '—' : x.toLocaleDateString('fr-FR', opts);
};
export const fmtDateTime = (d) => (d ? new Date(d).toLocaleString('fr-FR', { day: '2-digit', month: 'short', year: 'numeric', hour: '2-digit', minute: '2-digit' }) : '—');
export const fmtNum = (n) => new Intl.NumberFormat('fr-FR').format(n ?? 0);

export function timeAgo(d) {
  const s = (Date.now() - new Date(d).getTime()) / 1000;
  if (s < 60) return 'à l’instant';
  if (s < 3600) return `il y a ${Math.floor(s / 60)} min`;
  if (s < 86400) return `il y a ${Math.floor(s / 3600)} h`;
  if (s < 86400 * 30) return `il y a ${Math.floor(s / 86400)} j`;
  return fmtDate(d);
}

// Thème clair / sombre mémorisé par appareil.
export function initTheme() {
  try {
    const t = localStorage.getItem('ahl-theme');
    if (t) document.documentElement.dataset.theme = t;
  } catch { /* stockage indisponible */ }
}
export function toggleTheme() {
  const root = document.documentElement;
  const dark = root.dataset.theme ? root.dataset.theme === 'dark' : matchMedia('(prefers-color-scheme: dark)').matches;
  root.dataset.theme = dark ? 'light' : 'dark';
  try { localStorage.setItem('ahl-theme', root.dataset.theme); } catch { /* ignoré */ }
  return root.dataset.theme;
}
export const isDark = () => {
  const t = document.documentElement.dataset.theme;
  return t ? t === 'dark' : matchMedia('(prefers-color-scheme: dark)').matches;
};

// Redimensionne une image en JPEG carré (photo d'identité).
export function resizeImage(file, size = 320, quality = 0.82) {
  return new Promise((resolve, reject) => {
    const url = URL.createObjectURL(file);
    const img = new Image();
    img.onload = () => {
      const s = Math.min(img.width, img.height);
      const c = document.createElement('canvas');
      c.width = c.height = size;
      c.getContext('2d').drawImage(img, (img.width - s) / 2, (img.height - s) / 2, s, s, 0, 0, size, size);
      URL.revokeObjectURL(url);
      resolve(c.toDataURL('image/jpeg', quality));
    };
    img.onerror = () => { URL.revokeObjectURL(url); reject(new Error('Image illisible')); };
    img.src = url;
  });
}
